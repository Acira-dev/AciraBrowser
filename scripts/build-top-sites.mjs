// Builds desktop/browser-services/top-sites.cjs: Tranco's top registrable domains as hashes (threat-lists.cjs hashHost, 8 bytes each, sorted), the
// well-known sites whose whole host the Phishing.Database feed is never allowed to block (threat-lists.cjs, knownSite). Domains Acira's own look-alike
// check flags (googll.store, a typo of google.com that reached the top 10,000) are left out, so they stay blocked.
//   node scripts/build-top-sites.mjs [--top 10000] [--list <Tranco list id> | --tranco <top-1m.csv>]
// Without --list or --tranco the latest Tranco list is used and its id is written into the file, so the build can be repeated.
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {hashHost} = require('../desktop/browser-services/threat-lists.cjs'), {hostRisk} = require('../desktop/browser-services/page-risk.cjs');
const args = process.argv.slice(2), value = name => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
const top = Number(value('--top') || 10000), out = fileURLToPath(new URL('../desktop/browser-services/top-sites.cjs', import.meta.url));
const get = async url => { const response = await fetch(url, {signal: AbortSignal.timeout(120000), headers: {'user-agent': 'AciraBrowser top-sites build'}}); if (!response.ok) throw new Error(url + ': HTTP ' + response.status); return response.text(); };

let list = value('--list') || '', csv;
if (value('--tranco')) { csv = await fs.readFile(value('--tranco'), 'utf8'); list ||= 'local file'; }
else { list ||= (await get('https://tranco-list.eu/top-1m-id')).trim(); if (!/^[A-Z0-9]{4,8}$/.test(list)) throw new Error('Unexpected Tranco list id: ' + list); csv = await get(`https://tranco-list.eu/download/${list}/${top}`); }
const domains = [], left = [];
for (const line of csv.split('\n')) {
  const [place, name] = line.trim().split(','), domain = String(name || '').toLowerCase();
  if (!domain || !(Number(place) <= top) || !/^[a-z0-9.-]+\.[a-z0-9-]+$/.test(domain)) continue;
  if (hostRisk(domain)) left.push(domain); else domains.push(domain);
}
if (domains.length < top * 0.9) throw new Error(`Only ${domains.length} usable domains in the top ${top}.`);
const sorted = Float64Array.from(new Set(domains.map(hashHost))).sort();
const date = new Date().toISOString().slice(0, 10);
await fs.writeFile(out, `'use strict';
// Generated by scripts/build-top-sites.mjs on ${date} from the Tranco list ${list} (https://tranco-list.eu/list/${list}): the top ${top.toLocaleString('en')} registrable domains
// as threat-lists.cjs hashes (8 bytes each, sorted, base64), without the ${left.length} the look-alike check flags (${left.slice(0, 6).join(', ')}${left.length > 6 ? ', …' : ''}). Do not edit; rebuild.
module.exports = ${JSON.stringify({list, built: date, top, entries: sorted.length, hashes: Buffer.from(sorted.buffer).toString('base64')})};
`);
console.log(`[top-sites] ${sorted.length} domains from Tranco ${list} (top ${top}), ${left.length} look-alikes left out -> ${out}`);
