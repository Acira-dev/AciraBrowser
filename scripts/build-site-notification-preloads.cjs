'use strict';
// Writes the two site-notification preloads from desktop/browser-services/site-notification-wrappers.cjs: a sandboxed preload cannot require a file of
// its own, so each carries its wrapper's source inline (tests/site-notifications.test.cjs checks they still match). Run after editing the wrappers.
const fs = require('node:fs'), path = require('node:path');
const {pageWrapper, workerWrapper} = require('../desktop/browser-services/site-notification-wrappers.cjs');
const dir = path.join(__dirname, '..', 'desktop', 'browser-services');
const head = '\'use strict\';\n// GENERATED by scripts/build-site-notification-preloads.cjs from site-notification-wrappers.cjs: edit the wrappers, then run it.\n';
fs.writeFileSync(path.join(dir, 'site-notification-preload.cjs'), head + `// 14.3: a page's notifications go to Acira's own panel (desktop/site-notifications.cjs) while "Show site notifications" is In Acira. With "As system
// notifications" the page is left exactly as it was (nothing is wrapped: Chromium shows them as before). Registered on ordinary and private sessions only.
const {ipcRenderer, contextBridge} = require('electron');
if (/^https?:/.test(location.href)) {
  try {
    let mode = 'off'; try { mode = ipcRenderer.sendSync('acira:site-notification-mode'); } catch { mode = 'off'; }
    if (mode === 'acira') {
      const listeners = new Map();
      ipcRenderer.on('acira:site-notification-event', (_event, token, type) => { const fire = listeners.get(token); if (fire && (type === 'click' || type === 'close')) { try { fire(type); } catch { /* the page's handler threw */ } if (type === 'close') listeners.delete(token); } });
      const show = (note) => { try { ipcRenderer.send('acira:site-notification', note); } catch { /* a closing frame */ } };
      const permission = () => { try { const state = ipcRenderer.sendSync('acira:permission-state', 'notifications'); return state === 'granted' ? 'granted' : state === 'prompt' ? 'default' : 'denied'; } catch { return 'denied'; } };
      const subscribe = (token, fire) => { if (listeners.size >= 200) listeners.delete(listeners.keys().next().value); listeners.set(String(token).slice(0, 64), fire); };
      contextBridge.executeInMainWorld({func: ${pageWrapper.toString()}, args: [show, permission, subscribe]});
    }
  } catch { /* a closing frame */ }
}
`);
fs.writeFileSync(path.join(dir, 'site-notification-worker-preload.cjs'), head + `// 14.3: a service worker's notifications (self.registration.showNotification: Electron draws nothing for them) go to main, which puts them in Acira's panel,
// or, with "As system notifications", hands them to the system. Registered on ordinary and private sessions only (type 'service-worker').
const {ipcRenderer, contextBridge} = require('electron');
try {
  let fire = null;
  ipcRenderer.on('acira:site-notification-click', (_event, token) => { try { if (typeof fire === 'function') fire(String(token).slice(0, 64)); } catch { /* the worker's handler threw */ } });
  const send = (note) => { try { ipcRenderer.send('acira:site-notification-worker', note); } catch { /* a stopping worker */ } };
  const register = (dispatch) => { fire = dispatch; };
  const ask = () => ipcRenderer.invoke('acira:site-notification-permission').then(state => state === 'granted' ? 'granted' : state === 'prompt' ? 'default' : 'denied', () => 'denied');
  contextBridge.executeInMainWorld({func: ${workerWrapper.toString()}, args: [send, register, ask]});
} catch { /* the worker's own showNotification stays (Electron shows nothing for it) */ }
`);
console.log('site notification preloads written');
