// Writes src/runtime/publicSuffixTlds.ts: every top-level label of the Public Suffix List, read from the tldts copy already in
// node_modules (the main process uses tldts; the window only needs the top labels, ~10 KB instead of all of tldts).
// Run after updating tldts: node scripts/generate-public-suffix-tlds.mjs
import {createRequire} from 'node:module';
import {writeFileSync} from 'node:fs';
import {domainToASCII} from 'node:url';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const require = createRequire(import.meta.url);
const trie = require('tldts/dist/cjs/src/data/trie.js');
const {version} = require('tldts/package.json');
const offsets = [];
for (let node = 0, offset = 0; node < trie.nodeFlags.length; node += 1) for (let edge = trie.edgeStart[node]; edge < trie.edgeStart[node + 1]; edge += 1) { offsets[edge] = offset; offset += trie.edgeLength[edge]; }
const labels = new Set();
for (let edge = trie.edgeStart[trie.rulesRoot]; edge < trie.edgeStart[trie.rulesRoot + 1]; edge += 1) {
  const label = trie.labelText.substr(offsets[edge], trie.edgeLength[edge]);
  const ascii = domainToASCII(label);
  if (!ascii || ascii.includes('.')) throw new Error(`Unexpected top-level suffix ${label}`);
  labels.add(ascii.toLowerCase());
}
const sorted = [...labels].sort();
if (sorted.length < 1000 || !labels.has('com') || !labels.has('onion')) throw new Error(`Suffix list looks wrong (${sorted.length} labels)`);
const lines = [];
for (let index = 0; index < sorted.length; index += 24) lines.push(sorted.slice(index, index + 24).join(' '));
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/runtime/publicSuffixTlds.ts');
writeFileSync(out, `// Generated by scripts/generate-public-suffix-tlds.mjs from tldts ${version} (the Public Suffix List). Do not edit.\n// Top-level labels only, in ASCII (punycode for internationalized ones): ${sorted.length} labels.\nexport const PUBLIC_SUFFIX_TLDS = \`\n${lines.join('\n')}\n\`;\n`);
console.log(`${sorted.length} top-level suffixes -> ${path.relative(process.cwd(), out)}`);
