export function EngineMark({ engine, size = 24 }: { engine: keyof typeof engineMarks; size?: number }) {
  const mark = engineMarks[engine];
  return (
    <svg className="fr-mark-logo" width={size} height={size} viewBox="0 0 24 24" aria-hidden="true">
      <path d={mark.path} fill={mark.hex} />
    </svg>
  );
}

/** The account a source browser profile belongs to, as that browser shows it: the account picture when the browser
 * stored one, otherwise a circle in the profile's color with its initial (fields from stream D's profile identity). */
export function SourceAvatar({
  source,
  size = 24,
}: {
  source: { name: string; picture?: string; color?: string; fillColor?: string; initial?: string };
  size?: number;
}) {
  if (source.picture)
    return <img className="fr-avatar" src={source.picture} width={size} height={size} alt="" aria-hidden="true" />;
  const fill = isGreyProfileColor(source.color || source.fillColor) ? profileColorFor(source.name) : source.color || source.fillColor!;
  return (
    <span className="fr-avatar" style={{ width: size, height: size, background: fill, color: readable(fill), fontSize: Math.round(size * 0.46) }} aria-hidden="true">
      <bdi className="chip-letter">{source.initial || [...source.name.trim()][0]?.toLocaleUpperCase() || "?"}</bdi>
    </span>
  );
}

function readable(hex: string) {
  const match = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!match) return "#fff";
  const n = parseInt(match[1], 16),
    channel = (v: number) => {
      const c = v / 255;
      return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
    };
  const luminance = 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
  return luminance > 0.42 ? "#111113" : "#fff";
}

/** An installed browser's own icon when available, otherwise a neutral letter tile. */
export function BrowserIcon({ name, icon, size = 24 }: { name: string; icon?: string; size?: number }) {
  return icon ? (
    <img className="fr-mark-logo" src={icon} width={size} height={size} alt="" aria-hidden="true" />
  ) : (
    <span className="fr-glyph" style={{ width: size, height: size }} aria-hidden="true">
      {[...name.trim()][0]?.toLocaleUpperCase() || "?"}
    </span>
  );
}
