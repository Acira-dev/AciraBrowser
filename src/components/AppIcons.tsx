/** Compatibility with existing controls; every application glyph uses one editor family. */
function wrap(name:EditorIconName):LucideIcon {
 const Icon=forwardRef<SVGSVGElement,LucideProps>((props,ref)=>{
  const {size=16,strokeWidth,absoluteStrokeWidth,className='',style,...rest}=props;
  const pixels=Number.isFinite(Number(size))?Number(size):16;
  return <svg aria-hidden="true" {...rest} ref={ref} className={`ed-editor-icon ${className}`} style={{'--icon-size':`${pixels}px`,...style} as CSSProperties} width={pixels} height={pixels} viewBox="0 0 16 16" stroke="none" fill="currentColor"><EditorShape name={name}/></svg>;
 });Icon.displayName=`Editor${name}`;return Icon;
}
