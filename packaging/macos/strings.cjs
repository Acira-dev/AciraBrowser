function selectLocale(languages){for(const language of (Array.isArray(languages)?languages:[languages]).slice(0,32)){if(typeof language!=='string')continue;const base=language.trim().toLowerCase().split(/[-_]/)[0];if(Object.hasOwn(catalogs,base))return base;}return 'en';}
function text(locale,key){const row=catalogs[selectLocale(locale)];return row[key]||catalogs.en[key]||key;}
function failureKey(error){if(error?.code==='ACIRA_RUNNING')return 'running';if(error?.code==='ACIRA_PROCESS_CHECK_FAILED')return 'processCheckFailed';if(['EACCES','EPERM','EROFS'].includes(error?.code))return 'accessDenied';if(error?.code==='ENOSPC')return 'noSpace';if(/integrity|signature|codesign|payload|archive|missing|unsafe/i.test(String(error?.message||'')))return 'integrity';return 'failed';}
